function make(getLang) {
  return function t(key, vars = {}) {
    const lang = getLang() === 'pl' ? 'pl' : 'en';
    const s = T[lang][key] ?? T.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  };
}

